# 第 6 章的 R 圖檔產生程式(四大抽樣分配：標準常態、卡方、t、F；深色、淺色各一張，樣式見 theme.R)
# 用法(在 little-trader 資料夾下)：Rscript web/content/stats/basic/r/ch06-figures.R web/content/stats/basic/img
.dir <- dirname(sub("--file=", "", grep("--file=", commandArgs(FALSE), value = TRUE)))
source(file.path(.dir, "theme.R"))

lt_fig("ch06-sampling", 1040, 820, function(T) {
  par(mfrow = c(2, 2))
  # (1) 標準常態：雙尾 5% 的臨界值 ±1.96
  z <- seq(-4, 4, length.out = 400)
  lt_frame(T, c(-4, 4), c(0, 0.42), main = "Standard normal  Z ~ N(0, 1)", xlab = "z", ylab = "density")
  for (zz in list(seq(-4, -1.96, length.out = 100), seq(1.96, 4, length.out = 100)))
    polygon(c(zz[1], zz, zz[100]), c(0, dnorm(zz), 0), col = lt_alpha(T$red, 0.45), border = NA)
  lines(z, dnorm(z), lwd = 2.5, col = T$blue)
  abline(v = c(-1.96, 1.96), lty = 3, col = T$mute)
  text(c(-2.6, 2.6), 0.09, "2.5%", col = T$red, font = 2)
  text(0, 0.03, "-1.96 < z < 1.96: 95%", cex = 0.85, col = T$fg)
  # (2) 卡方：自由度越大越往右、越對稱(平均 k、變異數 2k)
  x <- seq(0.01, 20, length.out = 500)
  lt_frame(T, c(0, 20), c(0, 0.5), main = "Chi-square  chi^2(k)", xlab = "x", ylab = "density")
  cols <- c(T$blue, T$amber, T$red, T$green)
  for (i in 1:4) lines(x, dchisq(x, c(1, 3, 5, 10)[i]), lwd = 2.5, col = cols[i])
  lt_legend(T, "topright", c("k = 1", "k = 3", "k = 5", "k = 10"), cols, lwd = 2.5)
  # (3) t 分配 vs 標準常態：自由度小時尾巴較厚，自由度變大趨近常態
  lt_frame(T, c(-4, 4), c(0, 0.42), main = "t(df) vs N(0, 1)", xlab = "t", ylab = "density")
  lines(z, dnorm(z), lwd = 2.5, lty = 2, col = T$fg)
  lines(z, dt(z, 1), lwd = 2.5, col = T$red); lines(z, dt(z, 5), lwd = 2.5, col = T$amber); lines(z, dt(z, 30), lwd = 2.5, col = T$blue)
  lt_legend(T, "topright", c("N(0, 1)", "df = 1", "df = 5", "df = 30"), c(T$fg, T$red, T$amber, T$blue), lwd = 2.5, lty = c(2, 1, 1, 1))
  text(-4, 0.33, sprintf("2-sided 5%% critical value\ndf = 5: %.3f\ndf = 30: %.3f\nnormal: 1.960", qt(0.975, 5), qt(0.975, 30)), adj = 0, cex = 0.8, col = T$fg)
  # (4) F 分配：兩個卡方各除以自由度的比值，恆為正、右偏
  f <- seq(0.01, 5, length.out = 500)
  lt_frame(T, c(0, 5), c(0, 1.5), main = "F(d1, d2)", xlab = "F", ylab = "density")
  dd <- list(c(1, 10), c(5, 10), c(10, 30), c(30, 60))
  for (i in 1:4) lines(f, df(f, dd[[i]][1], dd[[i]][2]), lwd = 2.5, col = cols[i])
  lt_legend(T, "topright", c("F(1, 10)", "F(5, 10)", "F(10, 30)", "F(30, 60)"), cols, lwd = 2.5)
})
